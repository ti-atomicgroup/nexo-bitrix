import type {
  ActivityDefinition,
  AssigneeRole,
  JourneyTemplate,
  Visibility,
} from "../shared/contracts";

type StarterTemplate = Omit<JourneyTemplate, "version" | "updatedAt">;

function task(
  id: string,
  title: string,
  description: string,
  assigneeRole: AssigneeRole,
  offsetDays: number,
  visibility: Visibility,
  checklist: string[],
  critical = false,
  required = true,
): ActivityDefinition {
  return {
    id,
    title,
    description,
    assigneeRole,
    offsetDays,
    visibility,
    required,
    critical,
    checklist: checklist.map((title, index) => ({
      id: `${id}-check-${index + 1}`,
      title,
      required: true,
    })),
    documents: [],
  };
}

